import os
from openai import OpenAI

# Отримуємо ключ з Render Environment
OPENAI_API_KEY = os.getenv("OPENAI_API_KEY")

# Ініціалізація клієнта OpenAI
client = OpenAI(api_key=OPENAI_API_KEY)

# ------------------------------------------------------------------------
# 🪄 Основна універсальна функція виклику ChatGPT
# ------------------------------------------------------------------------
def _ask_openai(prompt: str, temperature: float = 0.85, model: str = "gpt-4o-mini") -> str:
    """
    Відправляє запит до ChatGPT та повертає відповідь.
    """
    try:
        response = client.chat.completions.create(
            model=model,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "Ти — містичний єнот 🦝✨, який відповідає українською "
                        "мовою і створює чарівні, теплі та гумористичні передбачення. "
                        "Твій стиль — дружній, з магічним шармом і легким гумором."
                    ),
                },
                {"role": "user", "content": prompt},
            ],
            temperature=temperature,
        )
        return response.choices[0].message.content.strip()
    except Exception as e:
        return f"⚠️ Єнот не зміг зв’язатись із ChatGPT: {e}"

# ------------------------------------------------------------------------
# 🃏 1. Індивідуальний AI-розклад
# ------------------------------------------------------------------------
def generate_ai_tarot(name: str, age: int = 25, topic: str = "кохання") -> str:
    prompt = (
        f"Створи персональний магічний розклад для {name}, {age} років. "
        f"Тема: {topic}. "
        "Напиши 7–10 речень: 1) загальна енергія; 2) поради; 3) попередження; 4) маленький ритуал. "
        "Тон — теплий, підтримуючий, магічний, без токсичного позитиву."
    )
    return _ask_openai(prompt)

# ------------------------------------------------------------------------
# ✋ 2. AI-Хіромантія
# ------------------------------------------------------------------------
def generate_ai_chiromancy(photo_description: str) -> str:
    prompt = (
        "На фото видно: " + photo_description + ". "
        "Опиши долоню — лінії життя, серця, розуму; темперамент, ресурси, поради на 8–12 речень. "
        "Додай м’яке застереження і маленьку практику для гармонії."
    )
    return _ask_openai(prompt)

# ------------------------------------------------------------------------
# 🌌 3. AI-Астрологічний прогноз
# ------------------------------------------------------------------------
def generate_ai_astrology(name: str, birthdate: str) -> str:
    prompt = (
        f"Користувач: {name}, дата народження: {birthdate}. "
        "Зроби прогноз на 10–12 речень про характер, кохання, кар’єру, фінанси та енергію місяця. "
        "Дай 3 конкретні поради та 1 обережність."
    )
    return _ask_openai(prompt)

# ------------------------------------------------------------------------
# 🔢 4. AI-Нумерологічний портрет
# ------------------------------------------------------------------------
def generate_ai_numerology(birthdate: str) -> str:
    digits = [int(c) for c in birthdate if c.isdigit()]
    n = sum(digits)
    while n > 9:
        n = sum(int(c) for c in str(n))

    prompt = (
        f"Число долі користувача — {n}. "
        "Опиши енергію числа, сильні сторони, виклики, місію та пораду. "
        "Напиши 7–9 речень у стилі єнота-нумеролога 🦝✨."
    )
    return _ask_openai(prompt)
